#!/usr/bin/env python3
"""
Analysis script for the Optimizer Comparison Experiment.
Reads fold_results.csv and training_history.csv generated by the experiment,
computes aggregate statistics, and generates comparison plots.
"""

import argparse
import os
import sys
import pandas as pd
import numpy as np

try:
    import matplotlib.pyplot as plt
    import seaborn as sns
    HAS_PLOTTING = True
except ImportError:
    HAS_PLOTTING = False


def parse_args():
    parser = argparse.ArgumentParser(description="Analyze optimizer comparison results.")
    parser.add_argument(
        "--results-dir",
        type=str,
        default="results/cross_validation/optimizer_comparison",
        help="Path to directory containing fold_results.csv and training_history.csv",
    )
    parser.add_argument(
        "--output-dir",
        type=str,
        default=None,
        help="Path to directory where plots and analysis will be saved (defaults to results-dir/plots)",
    )
    return parser.parse_args()


def main():
    args = parse_args()
    results_dir = args.results_dir
    output_dir = args.output_dir or os.path.join(results_dir, "plots")
    os.makedirs(output_dir, exist_ok=True)

    fold_csv = os.path.join(results_dir, "fold_results.csv")
    history_csv = os.path.join(results_dir, "training_history.csv")

    if not os.path.exists(fold_csv):
        print(f"Error: Could not find fold results file at {fold_csv}")
        sys.exit(1)

    df_folds = pd.read_csv(fold_csv)
    print("=" * 70)
    print("           OPTIMIZER COMPARISON - SUMMARY STATISTICS           ")
    print("=" * 70)

    summary = (
        df_folds.groupby("candidate")
        .agg(
            mean_val_mse=("validation_mse", "mean"),
            std_val_mse=("validation_mse", "std"),
            min_val_mse=("validation_mse", "min"),
            max_val_mse=("validation_mse", "max"),
            mean_train_mse=("train_mse", "mean"),
            fold_count=("fold", "count"),
        )
        .sort_values(by="mean_val_mse")
    )

    print(summary.to_string())
    print("\n" + "=" * 70)
    print("      TOP 3 BEST OPTIMIZERS FOR SUBSEQUENT GRID SEARCH        ")
    print("=" * 70)
    top3 = summary.head(3)
    for rank, (cand, row) in enumerate(top3.iterrows(), start=1):
        print(f"  #{rank} {cand:<35} | Mean Val MSE: {row['mean_val_mse']:.6f} +/- {row['std_val_mse']:.6f}")
    print("=" * 70)

    summary_csv = os.path.join(output_dir, "optimizer_summary_table.csv")
    summary.to_csv(summary_csv)
    top3_csv = os.path.join(output_dir, "top3_optimizers.csv")
    top3.to_csv(top3_csv)
    print(f"Summary table written to {summary_csv}")
    print(f"Top 3 table written to {top3_csv}")

    if HAS_PLOTTING:
        # Plot 1: Boxplot of validation MSE by candidate
        plt.figure(figsize=(10, 6))
        sns.boxplot(data=df_folds, x="candidate", y="validation_mse", palette="Blues_r")
        sns.stripplot(data=df_folds, x="candidate", y="validation_mse", color="black", alpha=0.6, jitter=0.2)
        plt.title("Cross-Validation Physical MSE across Folds by Optimizer", fontsize=13, fontweight="bold")
        plt.xlabel("Optimizer Candidate", fontsize=11)
        plt.ylabel("Validation Physical MSE", fontsize=11)
        plt.xticks(rotation=25, ha="right")
        plt.grid(True, linestyle="--", alpha=0.5)
        plt.tight_layout()
        boxplot_path = os.path.join(output_dir, "validation_mse_boxplot.png")
        plt.savefig(boxplot_path, dpi=300)
        plt.close()
        print(f"Boxplot saved to {boxplot_path}")

        # Plot 2: Convergence histories if available
        if os.path.exists(history_csv):
            df_hist = pd.read_csv(history_csv)
            if not df_hist.empty:
                plt.figure(figsize=(11, 6))
                sns.lineplot(
                    data=df_hist,
                    x="epoch",
                    y="validation_mse",
                    hue="candidate",
                    marker="o",
                    errorbar="sd",
                )
                plt.title("Validation Physical MSE Progression (Mean ± SD across folds)", fontsize=13, fontweight="bold")
                plt.xlabel("Epoch", fontsize=11)
                plt.ylabel("Validation Physical MSE (log scale)", fontsize=11)
                plt.yscale("log")
                plt.grid(True, which="both", linestyle="--", alpha=0.5)
                plt.legend(bbox_to_anchor=(1.02, 1), loc="upper left")
                history_path = os.path.join(output_dir, "learning_curves_val_mse.png")
                plt.savefig(history_path, dpi=300, bbox_inches="tight")
                plt.close()
                print(f"Learning curves saved to {history_path}")

    print("Analysis complete.")


if __name__ == "__main__":
    main()
